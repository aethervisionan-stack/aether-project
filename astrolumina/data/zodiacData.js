export function getSignByName(name) { return ZODIAC_DATA[name] || null; }

/** Grau solar aproximado (0–30) a partir de mês/dia no intervalo do signo. */
export function approxDegreeInSign(signName, month, day) {
  const s = ZODIAC_DATA[signName];
  if (!s) return 15;
  const [sm, sd] = s.dateRange.start;
  const [em, ed] = s.dateRange.end;
  const toDay = (m, d) => m * 31 + d;
  let start = toDay(sm, sd);
  let end = toDay(em, ed);
  let cur = toDay(month, day);
  if (end < start) { // wraps year (Cap)
    if (cur < start) cur += 12 * 31;
    end += 12 * 31;
  }
  const span = Math.max(1, end - start);
  const t = Math.min(1, Math.max(0, (cur - start) / span));
  return Math.min(29.9, t * 30);
}

export function decanForDegree(signName, degree) {
  const s = ZODIAC_DATA[signName];
  if (!s) return null;
  const d = Math.max(0, Math.min(29.999, degree));
  const idx = d < 10 ? 0 : d < 20 ? 1 : 2;
  return s.decans[idx];
}

export function getSunSign(month, day) {
  const ranges = [
    [1, 20, 'Capricórnio', 'Aquário'], [2, 19, 'Aquário', 'Peixes'], [3, 21, 'Peixes', 'Áries'],
    [4, 20, 'Áries', 'Touro'], [5, 21, 'Touro', 'Gêmeos'], [6, 21, 'Gêmeos', 'Câncer'],
    [7, 23, 'Câncer', 'Leão'], [8, 23, 'Leão', 'Virgem'], [9, 23, 'Virgem', 'Libra'],
    [10, 23, 'Libra', 'Escorpião'], [11, 22, 'Escorpião', 'Sagitário'], [12, 22, 'Sagitário', 'Capricórnio'],
  ];
  const [, cusp, before, after] = ranges[month - 1];
  return day < cusp ? before : after;
}
